#!/usr/bin/env python3.11
"""
RQ1 — Independent Deterministic Oracle Evaluation.

DESIGN: Avoids circular ground truth (GT generated by same extractor).

Independent oracle construction strategy:
  The JCL PRECEDES obligation A ≺ B is DERIVABLE directly from JCL grammar:
    - Any EXEC step following another EXEC step in the SAME JOB has an implicit
      ordering obligation: they execute in textual order.
    - COND= parameters create conditional execution obligations.

  The oracle is built by an INDEPENDENT REFERENCE IMPLEMENTATION
  that reads raw JCL text and extracts step orderings WITHOUT using
  StaticContractExtractor or BCGBuilder.

  This reference parser uses the SAME JCL grammar rules but is implemented
  independently in this file — it does not share code with the main pipeline.

  This eliminates the circular oracle problem: the reference implementation
  and the system under test share a SPECIFICATION (JCL grammar) but NOT code.

Independence guarantee:
  - Reference implementation: regex-based minimal JCL parser in THIS file only
  - System under test: StaticContractExtractor + BCGBuilder in src/
  - Both implement the same specification: JCL step ordering is textual order
  - Comparison: contract signatures (subject_name, predicate, object_name)
    are compared at the SEMANTIC level, not implementation level

Limitations (disclosed):
  - Only TEMPORAL (PRECEDES) contracts have fully deterministic oracle support
    from JCL grammar alone. RESOURCE and CONTROL_FLOW contracts require
    DD disposition analysis and COND= parsing, which share more implementation logic.
  - We clearly indicate which contract categories have independent oracle support.

Results: results/rq1/rq1_independent.json
"""

from __future__ import annotations

import json
import pathlib
import re
import sys
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "src"))

from legacy_contract.parsers.jcl_parser import JCLParser
from legacy_contract.static_analysis.extractor import StaticContractExtractor
from legacy_contract.bcg.builder import BCGBuilder
from legacy_contract.contracts.model import ContractType

OUTPUT_DIR = ROOT / "results" / "rq1"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# ---------------------------------------------------------------------------
# INDEPENDENT REFERENCE ORACLE (no shared code with main pipeline)
# ---------------------------------------------------------------------------

# JCL step name pattern: 1-8 chars, starts with alpha or @#$, uppercase
_JCL_STEP_RE = re.compile(
    r'^([A-Z@#\$][A-Z0-9@#\$]{0,7})\s+EXEC\s+',
    re.MULTILINE | re.IGNORECASE,
)

# JCL job card pattern
_JCL_JOB_RE = re.compile(
    r'^//([A-Z@#\$][A-Z0-9@#\$]{0,7})\s+JOB\s+',
    re.MULTILINE | re.IGNORECASE,
)

# JCL continuation/comment
_JCL_COMMENT_RE = re.compile(r'^//\*')

# COND= parameter detection
_JCL_COND_RE = re.compile(r'COND=\(', re.IGNORECASE)

# DD card
_JCL_DD_RE = re.compile(
    r'^//([A-Z@#\$][A-Z0-9@#\$]{0,7})\s+DD\s+',
    re.MULTILINE | re.IGNORECASE,
)


def _extract_step_names_from_jcl_text(text: str) -> list[str]:
    """
    Extract EXEC step names from raw JCL text in textual order.

    INDEPENDENT of main pipeline — uses only regex on raw text.
    Returns step names in the order they appear.
    """
    steps = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("//"):
            continue
        # Remove the '//' prefix
        content = stripped[2:]
        # Skip comments
        if content.startswith("*"):
            continue
        # Match: STEPNAME<whitespace>EXEC<whitespace>
        m = re.match(r'^([A-Z@#\$][A-Z0-9@#\$]{0,7})\s+EXEC\s+', content, re.IGNORECASE)
        if m:
            step_name = m.group(1).upper()
            steps.append(step_name)
    return steps


def _has_cond_parameter(text: str) -> bool:
    """Returns True if the JCL contains at least one COND= parameter."""
    return bool(_JCL_COND_RE.search(text))


def _build_oracle_contracts(step_names: list[str]) -> list[tuple[str, str, str]]:
    """
    Build oracle TEMPORAL contracts from step ordering.

    Returns list of (subject_name, predicate, object_name) tuples.
    A ≺ B means step A precedes step B.

    JCL semantics: steps execute in textual order within a job.
    Adjacent step pairs → MUST_PRECEDE contracts.
    """
    contracts = []
    for i in range(len(step_names) - 1):
        a = step_names[i]
        b = step_names[i + 1]
        if a != b:  # Skip reflexive pairs (duplicate step names — parse artifact, not a real obligation)
            contracts.append((a, "PRECEDES", b))
    return contracts


def _build_extractor_contracts(jcl_path: pathlib.Path, parser: JCLParser,
                                extractor: StaticContractExtractor,
                                builder: BCGBuilder) -> list[tuple[str, str, str]]:
    """
    Build contracts using the main pipeline (system under test).
    Returns list of (subject_name, predicate, object_name) tuples.
    """
    text = jcl_path.read_text(errors="replace").splitlines()
    try:
        jcl_rel = str(jcl_path.relative_to(ROOT))
    except ValueError:
        jcl_rel = str(jcl_path)
    _, ir = parser.parse_lines(text, jcl_rel)
    extraction = extractor.extract(ir)
    bcg = builder.build(ir, extraction)

    contracts = []
    entity_map = {eid: e for eid, e in bcg.entities.items()}

    for c in bcg.contracts.values():
        if c.contract_type.value != ContractType.TEMPORAL.value:
            continue
        subj = entity_map.get(c.subject_id)
        obj = entity_map.get(c.object_id)
        if subj and obj:
            contracts.append((subj.name.upper(), "PRECEDES", obj.name.upper()))

    return contracts


def _discover_held_out_jcl() -> list[pathlib.Path]:
    """Return held-out JCL files (test split, NOT used during development).

    BUG FIX (2026-08-30): SPLITS_60_20_20.json uses key 'held_out' not 'test'.
    Previous runs fell through to the fallback (all 33 app/jcl/*.jcl files),
    which includes dev-split files. The correct held-out set is 11 files with
    zero overlap with the dev (33) and validation (11) splits.
    """
    splits_file = ROOT / "datasets" / "carddemo" / "SPLITS_60_20_20.json"
    if splits_file.exists():
        with open(splits_file) as f:
            splits = json.load(f)
        # Primary key: 'held_out' (correct name in SPLITS_60_20_20.json)
        # Legacy fallback: 'test' (was wrong key; kept for backward compat)
        held_out_raw = splits.get("held_out", splits.get("test", []))
        test_paths = [
            pathlib.Path(p) for p in held_out_raw
            if p.lower().endswith(".jcl")
        ]
        # Resolve paths relative to dataset extraction base
        base = ROOT / "datasets/carddemo/extracted/aws-mainframe-modernization-carddemo-main"
        resolved = []
        for p in test_paths:
            if p.is_absolute() and p.exists():
                resolved.append(p)
            elif (base / p).exists():
                resolved.append(base / p)
            elif (ROOT / p).exists():
                resolved.append(ROOT / p)
        if resolved:
            return resolved

    # Fallback: use all JCL files (report limitation)
    print("WARNING: held_out split not resolved; falling back to all app/jcl/*.jcl")
    jcl_dir = (ROOT / "datasets/carddemo/extracted"
               / "aws-mainframe-modernization-carddemo-main/app/jcl")
    return list(jcl_dir.glob("*.jcl")) if jcl_dir.exists() else []


def _bootstrap_ci(values: list[float], n_boot: int = 10000, seed: int = 42) -> tuple[float, float]:
    """95% bootstrap CI for mean of values."""
    import random
    rng = random.Random(seed)
    if not values:
        return 0.0, 0.0
    boots = []
    for _ in range(n_boot):
        sample = [rng.choice(values) for _ in values]
        boots.append(sum(sample) / len(sample))
    boots.sort()
    lo = boots[int(0.025 * n_boot)]
    hi = boots[int(0.975 * n_boot)]
    return lo, hi


def main() -> None:
    print("=" * 60)
    print("RQ1 — INDEPENDENT ORACLE EVALUATION")
    print("=" * 60)
    print("Oracle: regex-based step-ordering extractor (independent)")
    print("System under test: StaticContractExtractor + BCGBuilder")
    print()

    jcl_files = _discover_held_out_jcl()
    print(f"JCL files (held-out/test split): {len(jcl_files)}")

    parser = JCLParser()
    extractor = StaticContractExtractor()
    builder = BCGBuilder()

    total_tp = 0
    total_fp = 0
    total_fn = 0

    per_file = []
    f1_scores = []

    for jcl_path in jcl_files:
        try:
            text_raw = jcl_path.read_text(errors="replace")

            # Oracle contracts (independent)
            oracle_steps = _extract_step_names_from_jcl_text(text_raw)
            oracle_contracts = set(_build_oracle_contracts(oracle_steps))

            # System contracts (main pipeline)
            system_contracts = set(
                _build_extractor_contracts(jcl_path, parser, extractor, builder)
            )

            # Normalize both for comparison
            oracle_sigs = {(a.upper(), p, b.upper()) for a, p, b in oracle_contracts}
            system_sigs = {(a.upper(), p, b.upper()) for a, p, b in system_contracts}

            tp = len(oracle_sigs & system_sigs)
            fp = len(system_sigs - oracle_sigs)  # System extracted but oracle doesn't have
            fn = len(oracle_sigs - system_sigs)  # Oracle has but system missed

            prec = tp / (tp + fp) if (tp + fp) > 0 else 1.0  # No FPs = precision 1.0
            rec = tp / (tp + fn) if (tp + fn) > 0 else 0.0
            f1 = 2 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0.0

            total_tp += tp
            total_fp += fp
            total_fn += fn
            f1_scores.append(f1)

            per_file.append({
                "file": jcl_path.name,
                "oracle_steps": oracle_steps,
                "oracle_contracts": len(oracle_contracts),
                "system_contracts": len(system_contracts),
                "tp": tp, "fp": fp, "fn": fn,
                "precision": round(prec, 4),
                "recall": round(rec, 4),
                "f1": round(f1, 4),
                "oracle_only": sorted([f"{a}→{b}" for a, _, b in (oracle_sigs - system_sigs)]),
                "system_only": sorted([f"{a}→{b}" for a, _, b in (system_sigs - oracle_sigs)]),
            })

        except Exception as exc:
            per_file.append({
                "file": jcl_path.name,
                "error": str(exc)[:200],
            })

    # Aggregate
    micro_prec = (total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 1.0)
    micro_rec = (total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0)
    micro_f1 = (2 * micro_prec * micro_rec / (micro_prec + micro_rec)
                if (micro_prec + micro_rec) > 0 else 0.0)

    macro_f1 = sum(f1_scores) / len(f1_scores) if f1_scores else 0.0
    f1_ci_lo, f1_ci_hi = _bootstrap_ci(f1_scores)

    # Count files where FP > 0 (system extracted contracts not in oracle)
    fp_files = [r for r in per_file if r.get("fp", 0) > 0]
    fn_files = [r for r in per_file if r.get("fn", 0) > 0]

    summary = {
        "experiment_id": "E1_INDEP",
        "research_question": "RQ1_independent_oracle",
        "run_timestamp": datetime.now(tz=timezone.utc).isoformat(),
        "seed": 42,
        "n_jcl_files": len(jcl_files),
        "oracle_type": "INDEPENDENT_REFERENCE_REGEX_IMPLEMENTATION",
        "oracle_independence_note": (
            "Oracle uses regex-based minimal JCL step-ordering parser implemented "
            "independently in this script. It shares the JCL SPEC (steps execute in "
            "textual order) but NOT code with StaticContractExtractor. This eliminates "
            "the circular evaluation problem present in Level-2 DETERMINISTIC GT."
        ),
        "contract_scope": "TEMPORAL_ONLY",
        "contract_scope_note": (
            "Only TEMPORAL (PRECEDES) contracts have deterministic oracle support "
            "from JCL step ordering alone. RESOURCE and CONTROL_FLOW contracts "
            "require DD disposition and COND= analysis which cannot be validated "
            "without sharing more implementation logic. Scope limitation is scientific."
        ),
        "micro_precision": round(micro_prec, 4),
        "micro_recall": round(micro_rec, 4),
        "micro_f1": round(micro_f1, 4),
        "macro_f1": round(macro_f1, 4),
        "f1_ci_lower": round(f1_ci_lo, 4),
        "f1_ci_upper": round(f1_ci_hi, 4),
        "bootstrap_n": 10000,
        "total_tp": total_tp,
        "total_fp": total_fp,
        "total_fn": total_fn,
        "files_with_fp": len(fp_files),
        "files_with_fn": len(fn_files),
        "hypothesis": "H1: micro_F1 >= 0.70, Precision >= 0.75",
        "h1_verdict": (
            "SUPPORTED" if micro_f1 >= 0.70 and micro_prec >= 0.75
            else "REJECTED"
        ),
        "fp_analysis": (
            "FP contracts are those extracted by the system but not present in the "
            "oracle. Possible causes: (a) system extracts non-adjacent PRECEDES "
            "derived from transitive ordering, which is a valid generalization but "
            "not in the minimal adjacent-step oracle; (b) parser artifacts."
            if total_fp > 0 else "No FP contracts detected — system matches oracle exactly."
        ),
        "fn_analysis": (
            "FN contracts are ordering obligations in the oracle that the system missed. "
            "Possible causes: (a) parse failure for specific JCL syntax; (b) step names "
            "extracted with different normalization."
            if total_fn > 0 else "No FN contracts — system captures all oracle contracts."
        ),
        "per_file": per_file,
    }

    out_path = OUTPUT_DIR / "rq1_independent.json"
    with open(out_path, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\nWrote → {out_path}")

    print("\n" + "=" * 60)
    print("RQ1 INDEPENDENT ORACLE RESULTS (TEMPORAL contracts only)")
    print("=" * 60)
    print(f"Files evaluated       : {len(jcl_files)}")
    print(f"Total TP              : {total_tp}")
    print(f"Total FP              : {total_fp}")
    print(f"Total FN              : {total_fn}")
    print(f"Micro Precision       : {micro_prec:.4f}")
    print(f"Micro Recall          : {micro_rec:.4f}")
    print(f"Micro F1              : {micro_f1:.4f}")
    print(f"Macro F1 (mean/file)  : {macro_f1:.4f}")
    print(f"F1 95% CI             : [{f1_ci_lo:.4f}, {f1_ci_hi:.4f}]")
    print(f"H1 verdict            : {summary['h1_verdict']}")
    print("=" * 60)

    if fp_files:
        print(f"\nFiles with FP (system extracted, oracle missing): {len(fp_files)}")
        for r in fp_files[:5]:
            print(f"  {r['file']}: FP={r['fp']} system_only={r.get('system_only', [])[:3]}")

    if fn_files:
        print(f"\nFiles with FN (oracle has, system missed): {len(fn_files)}")
        for r in fn_files[:5]:
            print(f"  {r['file']}: FN={r['fn']} oracle_only={r.get('oracle_only', [])[:3]}")


if __name__ == "__main__":
    main()
